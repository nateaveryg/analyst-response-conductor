func (h *ExportHandler) ExportRfiResponses(c *gin.Context) {
	format := strings.ToLower(c.DefaultQuery("format", "md"))
	report := c.DefaultQuery("report", "devsecops")
	isCNAP := strings.Contains(strings.ToLower(report), "cnap")

	rfiData, err := h.rfiArchitect.GenerateGroundedDrafts(c.Request.Context(), report)
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"detail": err.Error()})
		return
	}

	filePrefix := "gartner_rfi_completed_responses"
	if isCNAP {
		filePrefix = "gartner_cnap_rfi_completed_responses"
	}

	if format == "csv" {
		lines := []string{
			`"Worksheet Tab Domain","Section Coordinate","Question & Capability Requirement","Assigned SME Lead","Offered Natively","Prior RFI Source Title","Historical Question Match","Grounding Confidence Score","Pre-Populated Technical Draft Response"`,
		}
		for _, q := range rfiData.Questions {
			lines = append(lines, fmt.Sprintf(`"%s","%s","%s","%s","Yes (Native)","%s","%s","%.1f%%","%s"`,
				q.WorksheetTab, q.SectionID, q.QuestionText, q.AssignedSME, q.SourceRfiTitle, q.SourceQuestionText, q.GroundingConfidenceScore, q.DraftResponse))
		}
		csvContent := strings.Join(lines, "\n") + "\n"
		c.Header("Content-Disposition", fmt.Sprintf(`attachment; filename="%s.csv"`, filePrefix))
		c.Header("Cache-Control", "no-cache")
		c.Data(http.StatusOK, "text/csv; charset=utf-8", []byte(csvContent))
		return
	}

	nowStr := time.Now().UTC().Format("2006-01-02 15:04 UTC")
	lines := []string{
		"# 2026 Gartner Magic Quadrant & Critical Capabilities — Completed RFI Technical Responses",
		"**Generated By:** Principal TSA Sub-Agent Grounded RAG Ingestion  ",
		fmt.Sprintf("**Timestamp:** %s  ", nowStr),
		fmt.Sprintf("**Report Scope:** %s  ", rfiData.ReportName),
		fmt.Sprintf("**Average Grounding Confidence:** %.1f%% (Validated against verified GA Catalog)  ", rfiData.AverageGroundingConfidence),
		"",
		"## Summary Capability Evaluation Matrix",
		"",
		"| Worksheet Tab & Section | Requirement Question | Assigned SME | Offered Natively | Proven RAG Source & Grounding Score |",
		"| :--- | :--- | :---: | :--- | :---: |",
	}

	for _, q := range rfiData.Questions {
		lines = append(lines, fmt.Sprintf("| **%s** | %s | `%s` | **Yes (Native)** | *%s* (`%.1f%%`) |",
			q.SectionID, q.QuestionText, q.AssignedSME, q.SourceRfiTitle, q.GroundingConfidenceScore))
	}

	lines = append(lines, "", "---", "", "## Detailed Pre-Populated RAG Narratives by Worksheet Tab", "")
	for _, q := range rfiData.Questions {
		lines = append(lines,
			fmt.Sprintf("### %s — %s", q.SectionID, q.QuestionText),
			fmt.Sprintf("* **Assigned Domain Lead:** `%s`", q.AssignedSME),
			fmt.Sprintf("* **Grounding Confidence Score:** `%.1f%%`", q.GroundingConfidenceScore),
			fmt.Sprintf("* **Prior RFI Source Citation & Provenance:** `%s`", q.SourceRfiTitle),
			fmt.Sprintf("* **Grounded Technical Draft Response:**  \n  > %s (Backed by Google Cloud Support SLAs)", q.DraftResponse),
			"",
			"---",
			"",
		)
	}

	mdContent := strings.Join(lines, "\n")
	c.Header("Content-Disposition", fmt.Sprintf(`attachment; filename="%s.md"`, filePrefix))
	c.Header("Cache-Control", "no-cache")
	c.Data(http.StatusOK, "text/markdown; charset=utf-8", []byte(mdContent))
}

