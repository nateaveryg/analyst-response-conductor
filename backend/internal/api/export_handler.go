func (h *ExportHandler) ExportWorkbackSchedule(c *gin.Context) {
	format := strings.ToLower(c.DefaultQuery("format", "md"))
	targetDeadline := time.Date(2026, 6, 20, 17, 0, 0, 0, time.UTC)
	timeline := h.timeline.GenerateTimeline(targetDeadline, nil)

	if format == "csv" {
		lines := []string{"7-Phase Operational Process,Milestone Name,Offset (Days),Target Date,Shifted Status,Shift Reason"}
		for _, ms := range timeline.Milestones {
			dtStr := ms.TargetDate.Format("2006-01-02 15:04 UTC")
			shiftStatus := "On Schedule"
			if ms.Shifted {
				shiftStatus = "Shifted"
			}
			lines = append(lines, fmt.Sprintf(`"%s","%s",%d,%s,%s,"%s"`,
				ms.OperationalPhase, ms.Name, ms.OffsetDays, dtStr, shiftStatus, ms.ShiftReason))
		}
		csvContent := strings.Join(lines, "\n") + "\n"
		c.Header("Content-Disposition", `attachment; filename="universal_workback_schedule.csv"`)
		c.Header("Cache-Control", "no-cache")
		c.Data(http.StatusOK, "text/csv; charset=utf-8", []byte(csvContent))
		return
	}

	lines := []string{
		"# Universal Analyst Evaluation — Exclusive Workback Schedule",
		fmt.Sprintf("**Generated:** %s  ", time.Now().UTC().Format("2006-01-02 15:04 UTC")),
		fmt.Sprintf("**External Deadline:** %s  ", targetDeadline.Format("2006-01-02 15:04 UTC")),
		"**Active Exclusion Windows:** Cloud Next 2026 Conference Freeze (June 14–16, 2026)  ",
		"",
		"| 7-Phase Operational Process | Milestone / Activity | Offset | Target Date | Status & Blackout Shifts |",
		"| :--- | :--- | :---: | :---: | :--- |",
	}
	for _, ms := range timeline.Milestones {
		dtStr := ms.TargetDate.Format("2006-01-02")
		statusStr := "✅ On Schedule"
		if ms.Shifted {
			statusStr = fmt.Sprintf("⚠️ %s", ms.ShiftReason)
		}
		lines = append(lines, fmt.Sprintf("| **%s** | **%s** | `T-%d Days` | `%s` | %s |",
			ms.OperationalPhase, ms.Name, ms.OffsetDays, dtStr, statusStr))
	}
	lines = append(lines, "")
	mdContent := strings.Join(lines, "\n")

	c.Header("Content-Disposition", `attachment; filename="universal_workback_schedule.md"`)
	c.Header("Cache-Control", "no-cache")
	c.Data(http.StatusOK, "text/markdown; charset=utf-8", []byte(mdContent))
}

